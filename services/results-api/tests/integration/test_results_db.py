def test_get_existing_result(client, clean_db):
    seed(clean_db, row(device_id="ECU-042", verdict="FAIL"))

    response = client.get(f"{URL}/1")

    assert response.status_code == 200
    body = response.json()
    assert (body["id"], body["device_id"], body["verdict"]) == (1, "ECU-042", "FAIL")
    assert body["source"] == "simulator"


def test_get_nonexistent_result_returns_404(client, clean_db):
    seed(clean_db, row())

    response = client.get(f"{URL}/999")

    assert response.status_code == 404
    assert response.json() == {"detail": "Result not found"}
